"""Generate compact Cyrillic UI bitmaps from the Windows UI font (build-time only)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CHARS = ''.join(chr(c) for c in range(32, 127)) + ''.join(chr(c) for c in range(0x410, 0x450)) + 'Ёё'
out = ['// Generated by tools/generate_font.py; do not edit.', '#pragma once', '#include <stdint.h>',
       'struct UiGlyph { uint16_t code; uint16_t offset; uint8_t width; };']
for size in (14, 22):
    font = ImageFont.truetype('C:/Windows/Fonts/tahoma.ttf', size)
    height = size + 5
    data, glyphs = [], []
    for char in CHARS:
        width = max(2, int(font.getlength(char) + 1))
        im = Image.new('1', (width, height))
        ImageDraw.Draw(im).text((0, 0), char, font=font, fill=1)
        glyphs.append((ord(char), len(data), width))
        bits = [int(im.getpixel((x, y))) for y in range(height) for x in range(width)]
        for pos in range(0, len(bits), 8):
            byte = 0
            for bit, value in enumerate(bits[pos:pos+8]):
                byte |= value << (7-bit)
            data.append(byte)
    out.append(f'constexpr uint8_t uiBits{size}[] = {{' + ','.join(map(str,data)) + '};')
    out.append(f'constexpr UiGlyph uiGlyphs{size}[] = {{' + ','.join('{%d,%d,%d}' % g for g in glyphs) + '};')
(ROOT / 'include/ui_font_data.h').write_text('\n'.join(out)+'\n', encoding='utf-8')
print('Generated Cyrillic fonts')
